/* Generates hls/dvbt_tables.h for DVB-T 2K, 64-QAM, 7/8, GI 1/32, non-hierarchical.
 * Same algorithms as DVB-Tx_DUAL/engine/src/dvbt.c (EN 300 744). */
#include <stdio.h>
#include <string.h>

#define KMAX 1704
#define NDATA 1512
static const int cont_2k[45] = {
    0, 48, 54, 87, 141, 156, 192, 201, 255, 279, 282, 333, 432, 450, 483, 525, 531, 618, 636,
    714, 759, 765, 780, 804, 873, 888, 918, 939, 942, 969, 984, 1050, 1101, 1107, 1110, 1137,
    1140, 1146, 1206, 1269, 1323, 1377, 1491, 1683, 1704 };
static const int tps_2k[17] = {
    34, 50, 209, 346, 413, 569, 595, 688, 790, 901, 1073, 1219, 1262, 1286, 1469, 1594, 1687 };

int main(void)
{
    unsigned char wk[KMAX + 1], cont[KMAX + 1] = {0}, tps[KMAX + 1] = {0};
    unsigned reg = 0x7FF;
    for (int k = 0; k <= KMAX; k++) {
        wk[k] = reg & 1;
        unsigned nb = ((reg >> 2) ^ reg) & 1;
        reg = (reg >> 1) | (nb << 10);
    }
    for (int i = 0; i < 45; i++) cont[cont_2k[i]] = 1;
    for (int i = 0; i < 17; i++) tps[tps_2k[i]] = 1;

    /* data carriers below the centre (k < 852) for each symbol index mod 4 */
    int d0[4];
    for (int l = 0; l < 4; l++) {
        int n = 0, tot = 0;
        for (int k = 0; k <= KMAX; k++) {
            int pil = cont[k] || (k % 12 == 3 * l) || tps[k];
            if (!pil) { if (k < 852) n++; tot++; }
        }
        if (tot != NDATA) { fprintf(stderr, "bad count %d\n", tot); return 1; }
        d0[l] = n;
    }

    /* symbol interleaver H(q), 2K */
    static const int perm2k[10] = { 9, 6, 4, 1, 0, 7, 3, 8, 5, 2 };
    int H[NDATA], q = 0;
    unsigned rp = 0;
    for (int i = 0; i < 2048; i++) {
        if (i < 2) rp = 0;
        else if (i == 2) rp = 1;
        else { unsigned fb = (rp ^ (rp >> 3)) & 1; rp = (rp >> 1) | (fb << 9); }
        unsigned h = (unsigned)(i & 1) << 10;
        for (int j = 0; j < 10; j++) h |= ((rp >> perm2k[j]) & 1u) << j;
        if ((int)h < NDATA) H[q++] = (int)h;
    }
    if (q != NDATA) { fprintf(stderr, "bad H\n"); return 1; }

    /* TPS bits s0..s67 for the 4 frames of a superframe (cell id 0 signalled) */
    unsigned char tb[4][68];
    for (int m = 0; m < 4; m++) {
        unsigned char *s = tb[m];
        memset(s, 0, 68);
        int pos = 0;
#define PUT(val, nbits) do { for (int b_ = (nbits) - 1; b_ >= 0; b_--) s[pos++] = ((val) >> b_) & 1; } while (0)
        PUT(wk[0], 1);
        PUT((m & 1) ? 0xCA11 : 0x35EE, 16);
        PUT(0x1F, 6);     /* cell id signalled (= 0), as dvbt_ref.c */
        PUT(m, 2);
        PUT(2, 2);          /* 64-QAM */
        PUT(0, 3);          /* non-hierarchical */
        PUT(4, 3);          /* HP 7/8 */
        PUT(4, 3);          /* LP 7/8 */
        PUT(0, 2);          /* GI 1/32 */
        PUT(0, 2);          /* 2K */
        PUT(0, 8);          /* cell id */
        PUT(0, 6);
        unsigned r = 0;
        for (int i = 0; i < 113; i++) {
            unsigned in = i < 60 ? 0 : s[1 + i - 60];
            unsigned fb = (in ^ r) & 1;
            r >>= 1;
            r |= fb << 13;
            if (fb) r ^= (1u << 12) | (1u << 11) | (1u << 9) | (1u << 8) | (1u << 7) | (1u << 5) | (1u << 4);
        }
        for (int i = 0; i < 14; i++) s[54 + i] = (r >> i) & 1;
    }

    printf("/* Generated by gen/gen_tables.c - DVB-T 2K 64-QAM 7/8 GI 1/32 */\n#pragma once\n");
    printf("static const int D0[4] = { %d, %d, %d, %d };\n", d0[0], d0[1], d0[2], d0[3]);
    printf("/* bit0 continual pilot, bit1 TPS, bit2 wk (pilot PRBS) */\nstatic const ap_uint<3> CAR_ROM[%d] = {", KMAX + 1);
    for (int k = 0; k <= KMAX; k++) printf("%s%d,", k % 32 ? "" : "\n", cont[k] | tps[k] << 1 | wk[k] << 2);
    printf("\n};\nstatic const ap_uint<11> H_ROM[%d] = {", NDATA);
    for (int i = 0; i < NDATA; i++) printf("%s%d,", i % 16 ? " " : "\n", H[i]);
    printf("\n};\n/* TPS_ROM[frame][l] = s_l */\nstatic const ap_uint<1> TPS_ROM[4][68] = {\n");
    for (int m = 0; m < 4; m++) {
        printf("  {");
        for (int l = 0; l < 68; l++) printf("%d,", tb[m][l]);
        printf("},\n");
    }
    printf("};\n");
    return 0;
}
